"use client";

import { useState } from "react";
import { sessionsApi } from "@/lib/api";
import { useAuth } from "@/lib/auth-context";
import { BarChart } from "@/lib/charts";
import { inDateRange, toDateInput } from "@/lib/dates";
import { downloadReportPdf } from "@/lib/pdf";
import { ChartCard, CsvCell, Kv, Range, ReportFrame, ReportTable, downloadCsv, rangeLabel, slugDate } from "@/lib/report";
import { ErrorState, LoadingState } from "@/lib/states";
import { useApi } from "@/lib/use-api";

// R1: study sessions in the chosen period (default: the next 14 days).
export default function ScheduleReport() {
  const { user } = useAuth();
  const { data, error, loading, reload, reloading } = useApi("report-schedule", (t) => sessionsApi.list(t));
  const [range, setRange] = useState<Range>(() => {
    const today = new Date();
    return { from: toDateInput(today), to: toDateInput(new Date(today.getFullYear(), today.getMonth(), today.getDate() + 13)) };
  });

  if (loading) return <LoadingState label="Loading report" />;
  if (!data) return <ErrorState message={error ?? "Report unavailable."} onRetry={reload} retrying={reloading} />;

  const sessions = data.sessions
    .filter((s) => inDateRange(s.startsAt, range.from, range.to))
    .sort((a, b) => new Date(a.startsAt).getTime() - new Date(b.startsAt).getTime());
  const time = (iso: string) => new Date(iso).toLocaleTimeString(undefined, { hour: "2-digit", minute: "2-digit" });
  const minsOf = (s: (typeof sessions)[number]) => Math.round((new Date(s.endsAt).getTime() - new Date(s.startsAt).getTime()) / 60000);

  const rows: CsvCell[][] = sessions.map((s) => [
    new Date(s.startsAt).toLocaleDateString(undefined, { weekday: "short", day: "numeric", month: "short" }),
    `${time(s.startsAt)}-${time(s.endsAt)}`,
    s.task.title,
    s.task.subject?.name ?? "None",
    minsOf(s),
    s.completedAt ? "Done" : "Planned",
  ]);
  const head = ["Day", "Time", "Task", "Subject", "Minutes", "Status"];
  const totalMin = sessions.reduce((sum, s) => sum + minsOf(s), 0);
  const doneMin = sessions.filter((s) => s.completedAt).reduce((sum, s) => sum + minsOf(s), 0);

  // Minutes per day, in order, for the chart.
  const perDay = new Map<string, number>();
  for (const s of sessions) {
    const k = new Date(s.startsAt).toLocaleDateString(undefined, { day: "numeric", month: "short" });
    perDay.set(k, (perDay.get(k) ?? 0) + minsOf(s));
  }
  // One source for screen, CSV and PDF, so the three can never disagree.
  const summary: [string, string | number][] = [
    ["Sessions", sessions.length],
    ["Study days", perDay.size],
    ["Planned hours", (totalMin / 60).toFixed(1)],
    ["Completed hours", (doneMin / 60).toFixed(1)],
  ];
  const chartData = [...perDay.entries()].map(([label, value]) => ({ label, value }));

  return (
    <ReportFrame
      title="Study schedule"
      subtitle="Study sessions generated by the SchediQ scheduler"
      range={range}
      onRange={setRange}
      rangeHint="Filters by session date."
      onCsv={() => downloadCsv(`schediq-schedule-${slugDate()}.csv`, head, rows)}
      onPdf={() =>
        downloadReportPdf({
          filename: `schediq-schedule-${slugDate()}.pdf`,
          title: "Study schedule",
          subtitle: "Study sessions generated by the SchediQ scheduler",
          user,
          period: rangeLabel(range),
          summary,
          charts: [{ title: "Study minutes per day", data: chartData, unit: "minutes" }],
          tables: [{ title: "Sessions", head, rows, align: ["l", "l", "l", "l", "r", "l"] }],
        })
      }
    >
      <Kv items={summary} />
      <ChartCard title="Study minutes per day">
        <BarChart data={chartData} unit="minutes" ariaLabel="Study minutes per day" />
      </ChartCard>
      {rows.length === 0 ? (
        <p className="text-sm text-text-muted">No sessions in this period. Widen the dates or regenerate your schedule on the Dashboard.</p>
      ) : (
        <ReportTable head={head} rows={rows} align={["l", "l", "l", "l", "r", "l"]} />
      )}
    </ReportFrame>
  );
}
