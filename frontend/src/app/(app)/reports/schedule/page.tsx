"use client";

import { useEffect, useState } from "react";
import { ApiError, StudySession, sessionsApi } from "@/lib/api";
import { useAuth } from "@/lib/auth-context";
import { Kv, ReportFrame, ReportTable, downloadCsv, slugDate } from "@/lib/report";

// R1: upcoming (not yet completed, not yet ended) study sessions.
export default function ScheduleReport() {
  const { token } = useAuth();
  const [sessions, setSessions] = useState<StudySession[] | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!token) return;
    sessionsApi
      .list(token)
      .then((r) => {
        const now = Date.now();
        setSessions(r.sessions.filter((s) => !s.completedAt && new Date(s.endsAt).getTime() >= now));
      })
      .catch((err) => setError(err instanceof ApiError ? err.message : "Failed to load"));
  }, [token]);

  if (error) return <p className="text-sm text-red-600">{error}</p>;
  if (!sessions) return <p className="text-sm text-text-muted">Loading report...</p>;

  const time = (iso: string) => new Date(iso).toLocaleTimeString(undefined, { hour: "2-digit", minute: "2-digit" });
  const rows = sessions.map((s) => {
    const start = new Date(s.startsAt);
    const mins = Math.round((new Date(s.endsAt).getTime() - start.getTime()) / 60000);
    return [
      start.toLocaleDateString(undefined, { weekday: "short", day: "numeric", month: "short" }),
      `${time(s.startsAt)}-${time(s.endsAt)}`,
      s.task.title,
      s.task.subject?.name ?? "None",
      mins,
    ];
  });
  const totalMin = rows.reduce((sum, r) => sum + (r[4] as number), 0);
  const days = new Set(sessions.map((s) => new Date(s.startsAt).toDateString())).size;

  return (
    <ReportFrame
      title="Study schedule"
      subtitle="Upcoming study sessions generated by the SchediQ scheduler"
      onCsv={() =>
        downloadCsv(`schediq-schedule-${slugDate()}.csv`, ["Day", "Time", "Task", "Subject", "Minutes"], rows)
      }
    >
      <Kv items={[["Sessions", sessions.length], ["Study days", days], ["Planned hours", (totalMin / 60).toFixed(1)], ["Avg block (min)", sessions.length ? Math.round(totalMin / sessions.length) : 0]]} />
      {rows.length === 0 ? (
        <p className="text-sm text-text-muted">No upcoming sessions. Regenerate your schedule on the Dashboard.</p>
      ) : (
        <ReportTable head={["Day", "Time", "Task", "Subject", "Minutes"]} rows={rows} align={["l", "l", "l", "l", "r"]} />
      )}
    </ReportFrame>
  );
}
